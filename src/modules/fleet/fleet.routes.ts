import { Router } from "express";
import corrections from "./fleet-corrections.routes";
import { authenticate } from "../../middlewares/auth.middleware";
import { rateLimit } from "../../middlewares/rate-limit.middleware";
import { revision } from "../work/work.schemas";
import { fleetQuery, fuelSchema, voidSchema, waterPaymentSchema, waterSchema } from "./fleet.schemas";
import { listFuel, listWater, recordFuel, recordWater, settleWater, voidFuel, voidWater } from "./fleet.service";
import { departureSchema, listDepartures, recordDeparture, voidDeparture } from "./departures.service";
const router = Router();
router.use(authenticate);
router.use(corrections);
router.use(rateLimit({ windowMs: 60000, maxRequests: 180 }));
router.get("/departures", async (req, res) => { res.json(await listDepartures(fleetQuery.parse(req.query).page, req.user!)); });
router.post("/departures", async (req, res) => { res.status(201).json(await recordDeparture(departureSchema.parse(req.body), req.user!)); });
router.post("/departures/:id/void", async (req, res) => { const data = voidSchema.extend({ revision }).parse(req.body); res.json(await voidDeparture(String(req.params.id), data.revision, data.notes, req.user!)); });
router.get("/fuel", async (req, res) => { res.json(await listFuel(fleetQuery.parse(req.query), req.user!)); });
router.post("/fuel", async (req, res) => { res.status(201).json(await recordFuel(fuelSchema.parse(req.body), req.user!)); });
router.post("/fuel/:id/void", async (req, res) => { res.json(await voidFuel(String(req.params.id), voidSchema.parse(req.body).notes, req.user!)); });
router.get("/water", async (req, res) => { res.json(await listWater(fleetQuery.parse(req.query), req.user!)); });
router.post("/water", async (req, res) => { res.status(201).json(await recordWater(waterSchema.parse(req.body), req.user!)); });
router.post("/water/:id/payment", async (req, res) => { res.json(await settleWater(String(req.params.id), waterPaymentSchema.parse(req.body), req.user!)); });
router.post("/water/:id/void", async (req, res) => { const input = voidSchema.extend({ revision }).parse(req.body); res.json(await voidWater(String(req.params.id), input.revision, input.notes, req.user!)); });
export default router;
